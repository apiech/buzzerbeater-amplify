import { writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import {
  CloudFormationClient,
  DescribeStacksCommand,
} from "@aws-sdk/client-cloudformation";

import {
  loadBaseEnvFile,
  normalizeOptionalString,
  resolveMatchDataPlaneEnvFilePath,
  resolveMatchDataPlaneSource,
  resolveMatchDataPlaneStackName,
} from "./project-env.mjs";

const currentDir = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(currentDir, "..");

/**
 * @typedef {{
 *   describeStackOutputs: (args: { region?: string; stackName: string }) => Promise<Array<{ OutputKey?: string; OutputValue?: string }>>;
 *   env: Record<string, string | undefined>;
 *   writeFile: (filePath: string, contents: string) => Promise<void>;
 * }} SyncRuntime
 */

export const matchDataPlaneOutputEnvMap = [
  ["MatchStoreBucketName", "MATCH_STORE_BUCKET_NAME"],
  ["MatchCatalogTableName", "MATCH_CATALOG_TABLE_NAME"],
  ["TeamMatchProjectionTableName", "TEAM_MATCH_PROJECTION_TABLE_NAME"],
  ["ActiveTrackedTeamsTableName", "ACTIVE_TRACKED_TEAMS_TABLE_NAME"],
  ["PlayerSkillSnapshotTableName", "PLAYER_SKILL_SNAPSHOT_TABLE_NAME"],
  ["TeamMomentsTableName", "TEAM_MOMENTS_TABLE_NAME"],
  ["TeamHighlightsStatusTableName", "TEAM_HIGHLIGHTS_STATUS_TABLE_NAME"],
  ["TeamHighlightsScanQueueUrl", "TEAM_HIGHLIGHTS_SCAN_QUEUE_URL"],
];

export function renderMatchDataPlaneEnvFile(values) {
  return [
    "# Generated by `npm run sync:match-data-plane`.",
    "# Do not edit this file manually.",
    "",
    ...matchDataPlaneOutputEnvMap.map(
      ([, envName]) => `${envName}=${values[envName]}`,
    ),
    "",
  ].join("\n");
}

export function extractMatchDataPlaneEnvFromOutputs(outputs) {
  if (!Array.isArray(outputs)) {
    throw new Error("CloudFormation stack outputs were not an array.");
  }

  const outputValues = new Map();
  for (const output of outputs) {
    if (
      output &&
      typeof output === "object" &&
      typeof output.OutputKey === "string" &&
      typeof output.OutputValue === "string"
    ) {
      outputValues.set(output.OutputKey, output.OutputValue.trim());
    }
  }

  const envValues = {};
  const missingOutputs = [];
  for (const [outputKey, envName] of matchDataPlaneOutputEnvMap) {
    const value = normalizeOptionalString(outputValues.get(outputKey));
    if (!value) {
      missingOutputs.push(outputKey);
      continue;
    }
    envValues[envName] = value;
  }

  if (missingOutputs.length > 0) {
    throw new Error(
      `MatchDataPlane stack outputs are missing required values: ${missingOutputs.join(", ")}.`,
    );
  }

  return envValues;
}

export async function syncMatchDataPlaneConfig({
  projectRootPath = projectRoot,
  runtime = createDefaultRuntime(),
} = {}) {
  const source = resolveMatchDataPlaneSource(runtime.env);
  if (source !== "external") {
    return {
      skipped: true,
      source,
    };
  }

  const stackName = resolveMatchDataPlaneStackName(runtime.env);
  if (!stackName) {
    throw new Error(
      "MATCH_DATA_PLANE_STACK_NAME could not be resolved for external match-data-plane sync.",
    );
  }

  const outputs = await runtime.describeStackOutputs({
    region: resolveAwsRegion(runtime.env),
    stackName,
  });
  const envValues = extractMatchDataPlaneEnvFromOutputs(outputs);
  const envFilePath = resolveMatchDataPlaneEnvFilePath(projectRootPath);

  await runtime.writeFile(envFilePath, renderMatchDataPlaneEnvFile(envValues));
  return {
    envFilePath,
    envValues,
    skipped: false,
    stackName,
  };
}

export function resolveAwsRegion(env = process.env) {
  return (
    normalizeOptionalString(env.AWS_REGION) ??
    normalizeOptionalString(env.AWS_DEFAULT_REGION) ??
    undefined
  );
}

function createDefaultRuntime() {
  /** @type {SyncRuntime} */
  return {
    describeStackOutputs: async ({ region, stackName }) => {
      const client = new CloudFormationClient(region ? { region } : {});
      const response = await client.send(
        new DescribeStacksCommand({
          StackName: stackName,
        }),
      );
      return response.Stacks?.[0]?.Outputs ?? [];
    },
    env: process.env,
    writeFile: (filePath, contents) => writeFile(filePath, contents, "utf8"),
  };
}

export async function main() {
  loadBaseEnvFile(projectRoot);
  const result = await syncMatchDataPlaneConfig();
  if (result.skipped) {
    console.log(
      "Skipping external match-data-plane sync because MATCH_DATA_PLANE_SOURCE is not set to external.",
    );
    return;
  }

  console.log(
    `Wrote ${result.envFilePath} from CloudFormation stack ${result.stackName}.`,
  );
}

if (
  process.argv[1] &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1])
) {
  void main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  });
}
